import React, { useState } from 'react';
import { Header } from './components/Header';
import { PaperInput } from './components/PaperInput';
import { PaperMetaBanner } from './components/PaperMetaBanner';
import { CoreConceptView } from './components/CoreConceptView';
import { MermaidChart } from './components/MermaidChart';
import { InternshipProjectsView } from './components/InternshipProjectsView';
import { TokenBudgetGauge } from './components/TokenBudgetGauge';
import { RawPromptOutputModal } from './components/RawPromptOutputModal';
import { StudentAdvisorChat } from './components/StudentAdvisorChat';
import { CURATED_PAPERS } from './data/curatedPapers';
import { PaperAnalysisResult, CuratedPaper } from './types/paper';
import { Download, FileText, Sparkles, AlertCircle, RefreshCw } from 'lucide-react';

export default function App() {
  // Default to the first curated seminal paper (Mamba) for instant rich presentation
  const [currentAnalysis, setCurrentAnalysis] = useState<PaperAnalysisResult>(
    CURATED_PAPERS[0].defaultAnalysis
  );
  const [selectedCuratedId, setSelectedCuratedId] = useState<string>(CURATED_PAPERS[0].id);
  const [isLoading, setIsLoading] = useState<boolean>(false);
  const [loadingPhase, setLoadingPhase] = useState<string>('');
  const [error, setError] = useState<string | null>(null);

  // Modals & Panels state
  const [isRawModalOpen, setIsRawModalOpen] = useState<boolean>(false);
  const [isChatOpen, setIsChatOpen] = useState<boolean>(false);

  // Handler for custom paper analysis
  const handleAnalyze = async (payload: { url?: string; query?: string; pastedText?: string }) => {
    setIsLoading(true);
    setError(null);
    setSelectedCuratedId('');

    const phases = [
      'Ingesting paper metadata & abstract (token efficiency check)...',
      'Grounding with open-source repositories & system specifications...',
      'Step 1: Extracting Core Concepts (<300 words)...',
      'Step 2: Generating Mermaid.js Architectural Flowchart [graph TD]...',
      'Step 3: Brainstorming 3rd-year CS student resume projects...',
    ];

    let phaseIndex = 0;
    setLoadingPhase(phases[0]);
    const phaseInterval = setInterval(() => {
      phaseIndex = (phaseIndex + 1) % phases.length;
      setLoadingPhase(phases[phaseIndex]);
    }, 2800);

    try {
      const response = await fetch('/api/analyze-paper', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify(payload),
      });

      const json = await response.json();
      clearInterval(phaseInterval);

      if (!response.ok || json.error) {
        throw new Error(json.error || 'Failed to analyze paper.');
      }

      if (json.data) {
        setCurrentAnalysis(json.data);
      }
    } catch (err: any) {
      clearInterval(phaseInterval);
      console.error('Analysis failed:', err);
      setError(err.message || 'Analysis error occurred. Please check the URL or try again.');
    } finally {
      setIsLoading(false);
      setLoadingPhase('');
    }
  };

  // Handler for choosing a curated paper
  const handleSelectCurated = (paper: CuratedPaper) => {
    setSelectedCuratedId(paper.id);
    setCurrentAnalysis(paper.defaultAnalysis);
    setError(null);
  };

  // Download entire study report as markdown
  const handleExportFullMarkdown = () => {
    const content = `# CS Research Agent Analysis: ${currentAnalysis.paper.title}
Authors: ${currentAnalysis.paper.authors?.join(', ') || 'N/A'}
Domain: ${currentAnalysis.paper.primaryDomain || 'N/A'}
Original Link: ${currentAnalysis.paper.url || 'N/A'}

---

## 1. CORE CONCEPT EXTRACTION
${currentAnalysis.coreConcept.fullSummary}

**Problem Statement:**
${currentAnalysis.coreConcept.problemStatement}

**Primary Methodology:**
${currentAnalysis.coreConcept.primaryMethodology}

**Mathematical & Algorithmic Breakthroughs:**
${currentAnalysis.coreConcept.mathematicalBreakthroughs}

---

## 2. ARCHITECTURAL FLOWCHART (Mermaid.js)
\`\`\`mermaid
${currentAnalysis.architecturalFlowchart.mermaidCode}
\`\`\`

---

## 3. FUTURE WORK & INTERNSHIP OPPORTUNITIES (3rd-Year CS Student)
${currentAnalysis.internshipOpportunities
  .map(
    (opp, i) => `### Proposal ${i + 1}: ${opp.title}
- **Exact Extension:** ${opp.extension}
- **Targeted Performance Metric:** ${opp.targetMetric}
- **Recommended Tech Stack:** ${opp.techStack.join(', ')}
- **Resume STAR Bullet:** ${opp.resumeBullet || 'N/A'}
`
  )
  .join('\n')}

---
Generated by CS Research Agent • Monitored under 25,000 token operational constraint.
`;

    const blob = new Blob([content], { type: 'text/markdown;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.download = `${currentAnalysis.paper.title.replace(/[^a-z0-9]/gi, '_').toLowerCase()}_report.md`;
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
    URL.revokeObjectURL(url);
  };

  return (
    <div className="min-h-screen bg-[#070b14] text-slate-100 antialiased selection:bg-cyan-500/30 selection:text-cyan-200">
      {/* Top Header */}
      <Header
        tokenMetrics={currentAnalysis.tokenMetrics}
        onOpenRawOutput={() => setIsRawModalOpen(true)}
        onOpenAdvisorChat={() => setIsChatOpen(true)}
      />

      {/* Main Content Area */}
      <main className="mx-auto max-w-7xl px-4 py-8 sm:px-6 space-y-6">
        {/* Paper Input & Quick Presets Section */}
        <PaperInput
          onAnalyze={handleAnalyze}
          onSelectCurated={handleSelectCurated}
          isLoading={isLoading}
          selectedCuratedId={selectedCuratedId}
        />

        {/* Loading Progress State */}
        {isLoading && (
          <div className="rounded-2xl border border-indigo-500/40 bg-gradient-to-r from-indigo-950/40 via-slate-900 to-cyan-950/40 p-8 text-center shadow-xl shadow-indigo-500/10 backdrop-blur-sm animate-pulse">
            <div className="mx-auto mb-4 flex h-12 w-12 items-center justify-center rounded-2xl bg-indigo-600/20 text-indigo-400">
              <RefreshCw className="h-6 w-6 animate-spin" />
            </div>
            <h3 className="text-base font-bold text-white">
              CS Research Agent is Executing Analysis
            </h3>
            <p className="mt-2 text-xs font-mono text-cyan-300">
              {loadingPhase}
            </p>
            <p className="mt-3 text-[11px] text-slate-500">
              Honoring operational constraints: Token budget monitored &lt; 25,000 tokens • Parsing architecture
            </p>
          </div>
        )}

        {/* Error Notification */}
        {error && (
          <div className="flex items-center gap-3 rounded-xl border border-rose-500/40 bg-rose-950/30 p-4 text-xs text-rose-200">
            <AlertCircle className="h-5 w-5 text-rose-400 shrink-0" />
            <div className="flex-1">
              <p className="font-semibold text-rose-300">Analysis Request Failed</p>
              <p className="text-slate-300 mt-0.5">{error}</p>
            </div>
            <button
              onClick={() => setError(null)}
              className="rounded-lg bg-rose-900/40 px-2.5 py-1 text-[11px] font-medium text-rose-200 hover:bg-rose-900/60"
            >
              Dismiss
            </button>
          </div>
        )}

        {/* Paper Meta Banner */}
        <PaperMetaBanner paper={currentAnalysis.paper} />

        {/* Token Budget Gauge */}
        <TokenBudgetGauge metrics={currentAnalysis.tokenMetrics} />

        {/* Step 1: Core Concept Extraction */}
        <CoreConceptView
          coreConcept={currentAnalysis.coreConcept}
          paper={currentAnalysis.paper}
        />

        {/* Step 2: Architectural Flowchart (Mermaid.js) */}
        <MermaidChart
          flowchart={currentAnalysis.architecturalFlowchart}
          paperTitle={currentAnalysis.paper.title}
        />

        {/* Step 3: Future Work & Internship Projects */}
        <InternshipProjectsView
          opportunities={currentAnalysis.internshipOpportunities}
          paperTitle={currentAnalysis.paper.title}
        />

        {/* Bottom Utility Bar: Export Full Study Brief & Quick Chat */}
        <div className="flex flex-wrap items-center justify-between gap-4 rounded-xl border border-slate-800 bg-slate-900/40 p-4">
          <div className="flex items-center gap-2">
            <Sparkles className="h-4 w-4 text-cyan-400" />
            <span className="text-xs font-semibold text-slate-300">
              Complete Academic Study Brief Prepared
            </span>
          </div>

          <div className="flex items-center gap-3">
            <button
              onClick={handleExportFullMarkdown}
              className="flex items-center gap-1.5 rounded-lg border border-slate-700 bg-slate-800 px-3 py-1.5 text-xs font-medium text-slate-200 hover:bg-slate-700 hover:border-slate-600 transition"
            >
              <Download className="h-3.5 w-3.5" />
              <span>Export Full Brief (.md)</span>
            </button>

            <button
              onClick={() => setIsRawModalOpen(true)}
              className="flex items-center gap-1.5 rounded-lg border border-indigo-500/30 bg-indigo-950/40 px-3 py-1.5 text-xs font-medium text-indigo-300 hover:bg-indigo-900/40 transition"
            >
              <FileText className="h-3.5 w-3.5" />
              <span>View Raw Prompt Text</span>
            </button>

            <button
              onClick={() => setIsChatOpen(true)}
              className="flex items-center gap-1.5 rounded-lg bg-indigo-600 px-3 py-1.5 text-xs font-medium text-white hover:bg-indigo-500 transition shadow"
            >
              <Sparkles className="h-3.5 w-3.5" />
              <span>Ask CS Mentor</span>
            </button>
          </div>
        </div>
      </main>

      {/* Raw Prompt Output Modal */}
      <RawPromptOutputModal
        isOpen={isRawModalOpen}
        onClose={() => setIsRawModalOpen(false)}
        rawText={currentAnalysis.rawOutput}
        paperTitle={currentAnalysis.paper.title}
      />

      {/* Student Advisor Interactive Q&A Drawer */}
      <StudentAdvisorChat
        isOpen={isChatOpen}
        onClose={() => setIsChatOpen(false)}
        analysis={currentAnalysis}
      />
    </div>
  );
}
